"""Building a retrieval index over the manual, and measuring what it contains.

The statistics are not decoration. A chunker is a component whose output nobody
reads -- 15,000 passages go by and the only visible signal is that retrieval
feels about right -- so the way a chunking bug survives is by being invisible.
Counting the things that can go wrong, and recording those counts beside the
index, is what turns "the corpus looks fine" into a number that can move.

The counts that matter most are the ones that measure content *lost*: includes
that did not resolve, constants with no definition, role syntax that survived
the parse, code blocks that did not reach a chunk whole, and chunks so small
they cannot be retrieved. Each of them degrades a chunk into something that
still reads like documentation.
"""

from __future__ import annotations

import collections
import time
from dataclasses import dataclass, field
from typing import Any

from logtriage.embed.base import Embedder
from logtriage.kb.chunk import MAX_TOKENS, MIN_TOKENS, Chunk, chunk_blocks
from logtriage.kb.constants import SUBSTITUTION_RE
from logtriage.kb.corpus import Corpus
from logtriage.kb.parse import Block, count_residual_roles, parse_rst
from logtriage.store.knowledge import InMemoryKnowledgeStore

# Why an include target is absent. Every category here is a file the
# documentation toolchain generates during a build, or one that lives in another
# repository -- none of them are in a source checkout, and none can be recovered
# by reading harder. Naming them is what keeps "unresolved" from reading as
# "broken parser".
MISSING_AREAS = (
    ("/code-examples/", "code-examples: generated by the docs build"),
    ("/driver-examples/", "driver-examples: sourced from the driver repositories"),
    ("/includes/extracts/", "extracts: generated from includes/extracts-*.yaml"),
    ("/includes/release/", "release fragments: generated per release"),
)
OTHER_AREA = "other"


@dataclass(slots=True)
class IndexStats:
    """What one index build produced and what it could not resolve."""

    documents: int = 0
    chunks: int = 0
    token_min: int = 0
    token_p50: int = 0
    token_p95: int = 0
    token_max: int = 0
    over_max_tokens: int = 0
    under_min_tokens: int = 0
    with_code: int = 0
    code_blocks: int = 0
    code_blocks_intact: int = 0
    heading_depth: dict[int, int] = field(default_factory=dict)
    includes_resolved: int = 0
    includes_missing: int = 0
    missing_by_area: dict[str, int] = field(default_factory=dict)
    unknown_constants: tuple[str, ...] = ()
    unexpanded_substitutions: int = 0
    residual_roles: int = 0
    chunk_seconds: float = 0.0
    embed_seconds: float = 0.0

    def as_dict(self) -> dict[str, Any]:
        from dataclasses import asdict

        return asdict(self)


def classify_missing(target: str) -> str:
    for prefix, label in MISSING_AREAS:
        if target.startswith(prefix):
            return label
    return OTHER_AREA


def _percentile(values: list[int], fraction: float) -> int:
    if not values:
        return 0
    return values[min(int(len(values) * fraction), len(values) - 1)]


def _code_integrity(blocks: list[Block], chunks: list[Chunk]) -> tuple[int, int]:
    """How many of a page's code blocks reached a chunk whole.

    A code block is the actionable half of a diagnostic page -- the command that
    fixes the thing being diagnosed -- and half a command is worse than none,
    because it still looks runnable. The chunker is built never to split one, so
    this measures the property rather than assuming it: a block is intact if its
    text appears verbatim inside a single chunk. Truncation and splitting both
    break that; neither is visible any other way, because a chunk holding half a
    command reads exactly like a chunk holding a short one.
    """
    code = [block for block in blocks if block.kind == "code" and block.text]
    if not code:
        return 0, 0
    texts = [chunk.text for chunk in chunks]
    intact = sum(1 for block in code if any(block.text in text for text in texts))
    return len(code), intact


def chunk_corpus(corpus: Corpus) -> tuple[list[Chunk], IndexStats]:
    """Chunk every page, resolving includes as it goes."""
    stats = IndexStats()
    chunks: list[Chunk] = []

    started = time.monotonic()
    for path in corpus.pages():
        document = corpus.document_name(path)
        # Parsed and chunked in two steps rather than through chunk_document, so
        # the blocks are in hand for the integrity check without paying for a
        # second parse of the whole manual.
        blocks = parse_rst(corpus.read(path), document, resolver=corpus.resolve_include)
        page_chunks = chunk_blocks(blocks, document)
        total, intact = _code_integrity(blocks, page_chunks)
        stats.code_blocks += total
        stats.code_blocks_intact += intact
        chunks.extend(page_chunks)
        stats.documents += 1
    stats.chunk_seconds = time.monotonic() - started

    sizes = sorted(chunk.token_estimate for chunk in chunks)
    stats.chunks = len(chunks)
    stats.token_min = sizes[0] if sizes else 0
    stats.token_p50 = _percentile(sizes, 0.5)
    stats.token_p95 = _percentile(sizes, 0.95)
    stats.token_max = sizes[-1] if sizes else 0
    stats.over_max_tokens = sum(1 for size in sizes if size > MAX_TOKENS)
    stats.under_min_tokens = sum(1 for size in sizes if size < MIN_TOKENS)
    stats.with_code = sum(1 for chunk in chunks if chunk.has_code)
    stats.heading_depth = dict(
        sorted(collections.Counter(len(c.heading_path) for c in chunks).items())
    )

    stats.includes_resolved = corpus.stats.includes_resolved
    stats.includes_missing = corpus.stats.includes_missing
    areas = collections.Counter(
        classify_missing(target) for target in corpus.stats.missing_targets
    )
    stats.missing_by_area = dict(areas.most_common())
    stats.unknown_constants = tuple(sorted(corpus.stats.unknown_constants))
    stats.unexpanded_substitutions = sum(
        len(SUBSTITUTION_RE.findall(chunk.text)) for chunk in chunks
    )
    stats.residual_roles = sum(count_residual_roles(chunk.text) for chunk in chunks)
    return chunks, stats


def build_index(
    corpus: Corpus, embedder: Embedder
) -> tuple[InMemoryKnowledgeStore, IndexStats]:
    """Chunk, embed and index the whole manual."""
    chunks, stats = chunk_corpus(corpus)

    started = time.monotonic()
    vectors = embedder.embed([chunk.render() for chunk in chunks])
    stats.embed_seconds = time.monotonic() - started

    store = InMemoryKnowledgeStore()
    store.upsert(chunks, vectors)
    return store, stats
