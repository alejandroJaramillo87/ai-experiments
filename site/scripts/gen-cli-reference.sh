#!/bin/bash
# Regenerate the per-binary reference pages from each binary's own --help.
#
# The harness renders --help from the same table its parser reads
# (rust-harness/harness/src/cli.rs), and the seven runtime binaries do the same
# from their Spec (rust-harness/runtime/src/cli.rs), so --help is the one
# description of the command line that cannot drift from what is accepted.
# This script turns that text into a page rather than transcribing it, and
# scripts/docs/check_site_reference.py fails the quality gate when a page and
# its table disagree.
#
# The binary set is discovered, not listed: `harness` plus every file under
# runtime/src/bin/. A new binary gets a page on the next run without editing
# this script; sidebars.js still needs a line, and the build fails loudly on
# the missing page until it has one.
#
# Every binary answers --help before loading anything, so this needs no GPU,
# no checkpoint, and no network beyond what cargo needs to build.

set -euo pipefail

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
workspace="$repo_root/rust-harness"
out_dir="$repo_root/site/docs/rust-harness/reference"

if [ ! -f "$workspace/Cargo.toml" ]; then
  printf '[ERROR] site-gen: no rust-harness workspace at %s\n' "$workspace" >&2
  exit 1
fi

mkdir -p "$out_dir"

# One page for one binary. The page is front matter, a provenance line naming
# the source table so a reader who wants to change the text knows where it
# lives, and the help text in a fenced block.
write_page() {
  local name="$1" package="$2" source="$3"
  local page="$out_dir/$name.md"
  local help
  help="$(cargo run -q --manifest-path "$workspace/Cargo.toml" \
    -p "$package" --bin "$name" -- --help)"
  {
    printf -- '---\ntitle: %s\n---\n\n' "$name"
    printf '# %s\n\n' "$name"
    printf 'Generated by `make site-gen` from `%s --help`. Do not edit this page; ' "$name"
    printf 'edit the flag table in `%s` and regenerate.\n\n' "$source"
    printf '```text\n%s\n```\n' "$help"
  } > "$page"
  printf '[OK] %s\n' "${page#"$repo_root"/}"
}

write_page harness harness rust-harness/harness/src/cli.rs
for file in "$workspace"/runtime/src/bin/*.rs; do
  name="$(basename "$file" .rs)"
  write_page "$name" runtime "rust-harness/runtime/src/bin/$name.rs"
done
