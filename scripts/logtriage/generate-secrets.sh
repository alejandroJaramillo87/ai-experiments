#!/bin/bash
#
# Generate the three secrets the log triage stack needs, into .secrets/logtriage/.
#
# Nothing here is committed and nothing is derived from anything committed, so
# two machines running this get different credentials -- which is correct: the
# stack is a local deployment, not a distributed one, and a shared default
# password in a repository is a password that ends up on a server somewhere.
#
# Refuses to overwrite. Rotating means deleting the directory deliberately,
# because overwriting the keyfile of a running deployment breaks mongod and
# mongot apart, and overwriting the password file leaves mongot authenticating
# with a credential the deployment no longer holds.

set -euo pipefail

RED='\033[0;31m' GREEN='\033[0;32m' YELLOW='\033[1;33m'
BLUE='\033[0;34m' CYAN='\033[0;36m' NC='\033[0m'

if [[ -n "${NO_COLOR:-}" ]] || [[ "${1:-}" == "--no-color" ]]; then
    RED='' GREEN='' YELLOW='' BLUE='' CYAN='' NC=''
fi

print_ok()    { printf "${GREEN}[OK]${NC} %s\n" "$*"; }
print_warn()  { printf "${YELLOW}[WARN]${NC} %s\n" "$*"; }
print_error() { printf "${RED}[ERROR]${NC} %s\n" "$*"; }
print_info()  { printf "${CYAN}[INFO]${NC} %s\n" "$*"; }
print_run()   { printf "${BLUE}[RUN]${NC} %s\n" "$*"; }
print_skip()  { printf "${BLUE}[SKIP]${NC} %s\n" "$*"; }

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
SECRETS_DIR="${REPO_ROOT}/.secrets/logtriage"

# The uid the mongodb images run as. mongod refuses a keyfile it can read only
# through group or other permissions, so the file has to be mode 400 AND owned
# by this uid -- 400 owned by the host user is a permission denied at startup,
# which surfaces as a container that exits without an obvious reason.
MONGO_UID=999

echo "=== Log triage stack secrets ==="
echo

mkdir -p "$SECRETS_DIR"
chmod 700 "$SECRETS_DIR"

generated=0

# Shared secret authenticating mongod and mongot to each other. 756 bytes is
# the maximum mongod accepts, base64 so the file is printable ASCII.
if [[ -f "${SECRETS_DIR}/keyfile" ]]; then
    print_skip "keyfile: already present"
else
    print_run "keyfile: generating 756 bytes"
    openssl rand -base64 756 > "${SECRETS_DIR}/keyfile"
    chmod 400 "${SECRETS_DIR}/keyfile"
    generated=$((generated + 1))
fi

# The password mongot authenticates with. Written without a trailing newline:
# mongot reads the file verbatim, so a newline becomes part of the password and
# the failure is an authentication error with a correct-looking password file.
if [[ -f "${SECRETS_DIR}/passwordFile" ]]; then
    print_skip "passwordFile: already present"
else
    print_run "passwordFile: generating"
    openssl rand -base64 32 | tr -d '\n' > "${SECRETS_DIR}/passwordFile"
    chmod 400 "${SECRETS_DIR}/passwordFile"
    generated=$((generated + 1))
fi

# The root credential compose reads. Kept beside the other two rather than in
# the repository root so one directory holds everything secret about this stack.
if [[ -f "${SECRETS_DIR}/stack.env" ]]; then
    print_skip "stack.env: already present"
else
    print_run "stack.env: generating root credential"
    {
        printf '# Generated by scripts/logtriage/generate-secrets.sh. Never commit.\n'
        printf 'LOGTRIAGE_MONGO_ROOT_USER=logtriage\n'
        printf 'LOGTRIAGE_MONGO_ROOT_PASSWORD=%s\n' "$(openssl rand -base64 32 | tr -d '\n')"
    } > "${SECRETS_DIR}/stack.env"
    chmod 600 "${SECRETS_DIR}/stack.env"
    generated=$((generated + 1))
fi

echo
echo "Ownership:"
if [[ "$(stat -c '%u' "${SECRETS_DIR}/keyfile")" == "$MONGO_UID" ]]; then
    print_ok "keyfile: owned by uid ${MONGO_UID}"
else
    print_warn "keyfile: owned by uid $(stat -c '%u' "${SECRETS_DIR}/keyfile"), mongod runs as ${MONGO_UID}"
    echo "  mongod will exit at startup rather than read a keyfile it does not own."
    echo "  Solution: hand both files to the container user"
    echo "  Command: sudo chown ${MONGO_UID}:${MONGO_UID} ${SECRETS_DIR}/keyfile ${SECRETS_DIR}/passwordFile"
fi

echo
print_info "Secrets live in ${SECRETS_DIR} and are gitignored"
echo "  Summary: ${generated} generated, $((3 - generated)) already present"
echo
echo "Next:"
echo "  make logtriage-up"
echo "  make logtriage-bootstrap"
