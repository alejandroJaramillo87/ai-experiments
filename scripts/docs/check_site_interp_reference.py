#!/usr/bin/env python3
"""Fail the quality gate when a generated interp reference page and its module disagree.

site/docs/interp/reference/ carries one page per verb of the interp CLI, each
rendered from the CLI's own argparse parser by
scripts/docs/gen_site_interp_reference.py. The pages are committed so the site
builds without the Python environment, which is also how they drift: a flag
added to a module under interp/commands/ ships in the CLI and stays absent from
the page until somebody remembers to regenerate.

This gate is the reminder, and it runs without importing the package. It reads
each command module as text: the first `add_parser("<verb>")` literal names the
module's verb, every `add_argument("--x")` literal is a flag the verb accepts
(nested subcommands, as in organism, fold into the one page), and a module that
delegates its parser to common/obs (`runs.configure(sub, "interp")`) is read
from that module instead. It then asks three things of the reference directory:
every verb has a page, every page that says it was generated names a verb that
still exists, and every flag literal appears on its page. A page cannot carry a
flag the module does not accept, because the page is rendered from the module's
own parser; so the one direction left to check is the module carrying a flag
the page does not show.

What this is not: a check that the rendering itself is current. That is
tests/docs/test_gen_site_interp_reference.py, which pins the page shape against
a fixture parser. This gate holds the committed copy of a rendering to the
source it was rendered from.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent.parent
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from common.output import Printer  # noqa: E402

COMMANDS_DIR = Path("interp") / "commands"
DELEGATE_DIR = Path("common") / "obs"
REFERENCE_DIR = Path("site") / "docs" / "interp" / "reference"

# The two argparse literals, as the modules write them. Kept as regexes over
# text rather than an import of the package because scripts/docs/ runs as
# standalone scripts and the gate must not depend on the interp environment.
VERB_LITERAL = re.compile(r'add_parser\(\s*"([a-z][a-z0-9-]*)"')
FLAG_LITERAL = re.compile(r'add_argument\(\s*(?:"-[a-z]",\s*)?"(--[a-z0-9-]+)"')
DELEGATE = re.compile(r'\b([a-z_]+)\.configure\(sub,\s*"interp"\)')

# The provenance line gen_site_interp_reference.py writes. A page carrying it
# claims to be generated; a page without it is hand-written and not this gate's.
GENERATED_MARKER = "Generated by `make site-gen`"


def surface(root: Path) -> dict[str, tuple[Path, set[str]]]:
    """Each verb, mapped to the source file that defines it and its flag literals."""
    verbs: dict[str, tuple[Path, set[str]]] = {}
    commands = root / COMMANDS_DIR
    if not commands.is_dir():
        return verbs
    for source in sorted(commands.glob("*.py")):
        if source.name == "__init__.py":
            continue
        text = source.read_text(encoding="utf-8")
        delegate = DELEGATE.search(text)
        if delegate:
            # The delegated module also has a standalone entry point whose own
            # flags (`--cli`) the verb never sees; read only what precedes it.
            source = root / DELEGATE_DIR / f"{delegate.group(1)}.py"
            text = source.read_text(encoding="utf-8").split("\ndef main(", 1)[0]
        verb = VERB_LITERAL.search(text)
        if not verb:
            continue
        verbs[verb.group(1)] = (source, set(FLAG_LITERAL.findall(text)))
    return verbs


def generated_pages(root: Path) -> dict[str, Path]:
    """Every page under the reference directory that says it was generated."""
    pages: dict[str, Path] = {}
    directory = root / REFERENCE_DIR
    if not directory.is_dir():
        return pages
    for page in sorted(directory.glob("*.md")):
        if GENERATED_MARKER in page.read_text(encoding="utf-8"):
            pages[page.stem] = page
    return pages


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--root", type=Path, default=REPO_ROOT, help="repository root to scan"
    )
    args = parser.parse_args()
    root = args.root.resolve()
    out = Printer()

    verbs = surface(root)
    pages = generated_pages(root)

    # The empty-set guard. An enumeration that finds no verbs would report
    # every page as orphaned and no flag as missing, which is not a result.
    if not verbs:
        out.error("site-interp-reference: enumerated no interp verbs")
        out.line("  The gate would pass without checking anything.")
        out.line(f'  Expected `add_parser("<verb>")` literals under {root / COMMANDS_DIR}')
        return 1
    if not pages:
        out.error(f"site-interp-reference: no generated pages under {REFERENCE_DIR}")
        out.line("  Solution: regenerate them")
        out.line("  Command: make site-gen")
        return 1

    missing_pages = sorted(name for name in verbs if name not in pages)
    orphan_pages = sorted(name for name in pages if name not in verbs)
    missing_flags: list[tuple[str, str]] = []
    for name, (_, flags) in sorted(verbs.items()):
        page = pages.get(name)
        if page is None:
            continue
        text = page.read_text(encoding="utf-8")
        for flag in sorted(flags):
            # Whole-flag match: `--model` must not be satisfied by `--model-hash`.
            if not re.search(rf"{re.escape(flag)}(?![\w-])", text):
                missing_flags.append((name, flag))

    flag_total = sum(len(flags) for _, flags in verbs.values())
    out.info(
        f"site-interp-reference: {len(verbs)} verbs, {flag_total} flags, "
        f"against {len(pages)} generated pages"
    )

    if not missing_pages and not orphan_pages and not missing_flags:
        out.ok("site-interp-reference: every verb has a page that shows every flag")
        return 0

    total = len(missing_pages) + len(orphan_pages) + len(missing_flags)
    noun = "finding" if total == 1 else "findings"
    out.error(f"site-interp-reference: {total} {noun}")
    for name in missing_pages:
        source = verbs[name][0].relative_to(root)
        out.line(f"  no page for verb {name} ({source})")
    for name in orphan_pages:
        page = pages[name].relative_to(root)
        out.line(f"  page {page} names no verb")
    for name, flag in missing_flags:
        out.line(f"  flag {flag} of {name} is absent from its page")
    out.line("  Solution: regenerate the reference pages from the parser")
    out.line("  Command: make site-gen")
    return 1


if __name__ == "__main__":
    sys.exit(main())
