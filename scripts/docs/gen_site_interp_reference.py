#!/usr/bin/env python3
"""Render site/docs/interp/reference/<verb>.md from the interp CLI's own parser.

The interp CLI is one argparse parser (interp/cli.py, build_parser) with one
subcommand per module under interp/commands/, and --help is rendered from that
parser, so the parser is the one description of a verb's command line that
cannot drift from what is accepted. Where the rust-harness generator has to
parse --help text because neither crate has a machine-readable form, this one
walks the parser object: each verb's description, its usage line, and one table
row per argument, with the default the parser would apply.

interp/cli.py keeps every heavy import lazy inside the handlers, so building the
parser needs the sandbox dependency group and nothing else: no torch, no GPU,
no model. scripts/docs/check_site_interp_reference.py fails the quality gate
when a page and its module disagree.

The verb set is discovered from interp.cli.COMMAND_MODULES: each module's
configure() registers exactly one verb, and that pairing is what names the
source file on the page. A verb with nested subcommands (organism) renders as
one page with one section per subcommand.

Usage:
  python scripts/docs/gen_site_interp_reference.py [--root <repo>]
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent.parent
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from common.output import Printer  # noqa: E402

REFERENCE_DIR = Path("site") / "docs" / "interp" / "reference"
PROG = "python -m interp"


def cell(text: str) -> str:
    """Escape prose for a table cell: a pipe would split it, a bracket is HTML."""
    return text.replace("|", "\\|").replace("<", "&lt;").replace(">", "&gt;")


def code_cell(text: str) -> str:
    """Escape a backticked cell: inside a table a pipe splits even within code."""
    return "`" + text.replace("|", "\\|") + "`"


def subparsers_of(parser: argparse.ArgumentParser) -> argparse._SubParsersAction | None:
    """The subcommand action of a parser, or None when it has no subcommands."""
    for action in parser._actions:
        if isinstance(action, argparse._SubParsersAction):
            return action
    return None


def term(action: argparse.Action) -> str:
    """The flag as the help shows it: every spelling, then the value placeholder."""
    flags = ", ".join(action.option_strings)
    if action.nargs == 0:
        return flags
    metavar = action.metavar or action.dest.upper()
    return f"{flags} {metavar}"


def default_cell(action: argparse.Action) -> str:
    """What the parser applies when the flag is absent, or `required`."""
    if action.required:
        return "required"
    default = action.default
    if default is argparse.SUPPRESS or default is None or default == [] or default == "":
        return ""
    if action.nargs == 0 and isinstance(default, bool):
        # A store_true flag's default is the absence of the flag; saying
        # "False" in the table would describe the implementation, not a value.
        return ""
    return code_cell(str(default))


def render_table(parser: argparse.ArgumentParser) -> list[str]:
    """One row per argument, in the order the parser registered them."""
    out = ["| Flag | Description | Default |", "|------|-------------|---------|"]
    for action in parser._actions:
        if isinstance(action, argparse._SubParsersAction):
            continue
        if action.dest == "help":
            continue
        out.append(
            f"| {code_cell(term(action))} | {cell(action.help or '')} | {default_cell(action)} |"
        )
    out.append("")
    return out


def render_section(parser: argparse.ArgumentParser, level: str) -> list[str]:
    """Description, usage, and the flag table of one parser."""
    out: list[str] = []
    if parser.description:
        for paragraph in parser.description.strip().split("\n\n"):
            out += [" ".join(line.strip() for line in paragraph.splitlines()), ""]
    out += [f"{level} Usage", "", "```text", parser.format_usage().rstrip(), "```", ""]
    out += [f"{level} Flags", ""]
    out += render_table(parser)
    return out


def render_page(verb: str, source: str, parser: argparse.ArgumentParser) -> str:
    """The page for one verb, with nested subcommands as sections."""
    out: list[str] = [
        "---",
        f"title: {verb}",
        "---",
        "",
        f"# {verb}",
        "",
        f"Generated by `make site-gen` from `{PROG} {verb} --help`. Do not edit this page; "
        f"edit the parser in `{source}` and regenerate.",
        "",
    ]
    nested = subparsers_of(parser)
    if nested is None:
        out += render_section(parser, "##")
    else:
        if parser.description:
            out += [parser.description.strip(), ""]
        out += ["## Usage", "", "```text", parser.format_usage().rstrip(), "```", ""]
        out += [
            "Each subcommand has its own flags; the sections below are in the order the "
            "parser lists them.",
            "",
        ]
        for name, sub in nested.choices.items():
            out += [f"## {verb} {name}", ""]
            out += render_section(sub, "###")
    return "\n".join(out).rstrip() + "\n"


def verbs(root: Path) -> list[tuple[str, str, argparse.ArgumentParser]]:
    """Each verb as (name, source path relative to root, its parser).

    Every module in COMMAND_MODULES registers one verb on a subparser; feeding
    each module a fresh subparser is what pairs a verb with its source file
    without a second table to keep in step.
    """
    from interp import cli

    found: list[tuple[str, str, argparse.ArgumentParser]] = []
    for module in cli.COMMAND_MODULES:
        probe = argparse.ArgumentParser(prog=PROG)
        sub = probe.add_subparsers(dest="command")
        module.configure(sub)
        names = list(sub.choices)
        if len(names) != 1:
            raise ValueError(f"{module.__name__} registers {len(names)} verbs, expected 1")
        source = Path(module.__file__).resolve().relative_to(root)
        found.append((names[0], str(source), sub.choices[names[0]]))
    return found


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--root", type=Path, default=REPO_ROOT, help="repository root to write under"
    )
    args = parser.parse_args()
    root = args.root.resolve()
    out = Printer()

    found = verbs(REPO_ROOT)
    if not found:
        out.error("site-gen: interp.cli.COMMAND_MODULES is empty")
        return 1
    out_dir = root / REFERENCE_DIR
    out_dir.mkdir(parents=True, exist_ok=True)
    for verb, source, verb_parser in found:
        page = out_dir / f"{verb}.md"
        page.write_text(render_page(verb, source, verb_parser), encoding="utf-8")
        out.ok(f"{page.relative_to(root)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
