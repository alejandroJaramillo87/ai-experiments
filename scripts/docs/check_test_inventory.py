#!/usr/bin/env python3
"""Fail the quality gate when tests/training/README.md and its test files disagree.

The inventory table in tests/training/README.md is generated by
scripts/docs/gen_test_inventory.py from the module docstrings of the test files
themselves. It is committed so a reader gets the directory's contents without
running anything, which is also how it goes stale: a test module added, renamed,
or given a sharper docstring ships with the change and leaves the table
describing the directory as it was.

A hand-maintained inventory has the same failure in a worse form. It is true on
the day it is written, and the description it carries is a second copy of
something the test file already states in its first line -- so the two are
edited at different moments and only one of them is the one anyone reads.

This gate is the reminder. It runs the generator's --check against `training`:
regenerate the table in memory, diff it against what is committed, and report
the difference rather than only that there is one. Nothing here needs torch, a
GPU, or a collected test session, because the inputs are the files' ASTs.
"""

from __future__ import annotations

import argparse
import importlib.util
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent.parent
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from common.output import Printer  # noqa: E402

GENERATOR = Path(__file__).resolve().parent / "gen_test_inventory.py"

# The directory whose inventory is gated. Adding one here is the whole cost of
# extending the gate; the generator already takes any directory under tests/.
GATED_DIRS = ("training",)


def load_generator(path: Path):
    """Load the generator by path; scripts/ is not an importable package."""
    spec = importlib.util.spec_from_file_location("gen_test_inventory", path)
    if spec is None or spec.loader is None:
        raise ImportError(f"cannot load {path}")
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--root", type=Path, default=REPO_ROOT, help="repository root to scan"
    )
    args = parser.parse_args()
    out = Printer()

    if not GENERATOR.is_file():
        out.error(f"test-inventory: no generator at {GENERATOR}")
        return 1

    generator = load_generator(GENERATOR)
    status = 0
    for directory in GATED_DIRS:
        argv = [
            str(GENERATOR),
            "--root",
            str(args.root),
            "--dir",
            directory,
            "--check",
        ]
        saved, sys.argv = sys.argv, argv
        try:
            status |= generator.main()
        finally:
            sys.argv = saved
    return 1 if status else 0


if __name__ == "__main__":
    sys.exit(main())
