#!/usr/bin/env python3
"""Fail the quality gate when a generated site reference page and its binary disagree.

site/docs/rust-harness/reference/ carries one page per rust-harness binary,
each rendered from that binary's --help by scripts/docs/gen_site_reference.py:
the usage line, then one table per help section. The pages are committed so
the site builds without cargo, which is also how they drift: a flag added to
the table in harness/src/cli.rs or a bin's Spec ships in the binary and stays
absent from the page until somebody remembers to regenerate.

This gate is the reminder, and it runs without cargo or node. It enumerates the
binaries and their `Flag { name: "--x" }` literals the way check_surface_census.py
does -- the same eight files, the same regex -- and asks three things of the
reference directory: every binary has a page, every page that says it was
generated names a binary that still exists, and every flag literal of a binary
appears in its page. A page cannot carry a flag the binary does not accept,
because the page is rendered from the binary's own --help; so the one
direction left to check is the binary carrying a flag the page does not show.

What this is not: a check that --help itself is current. That is the golden
tests in rust-harness/harness/tests/cli_surface.rs, which pin the rendering
against the table. This gate holds the committed copy of that rendering to the
table it was rendered from.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent.parent
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from common.output import Printer  # noqa: E402

# The `Flag` literal, as check_surface_census.py reads it. Kept as a second
# copy rather than an import because scripts/docs/ is not a package and the
# gates are run as standalone scripts.
FLAG_LITERAL = re.compile(r'name:\s*"(--[a-z0-9-]+)"')

# The provenance line gen_site_reference.py writes. A page carrying it claims
# to be generated; a page without it is hand-written and not this gate's.
GENERATED_MARKER = "Generated by `make site-gen`"

REFERENCE_DIR = Path("site") / "docs" / "rust-harness" / "reference"


def surface(root: Path) -> dict[str, tuple[Path, set[str]]]:
    """Each shipped binary, mapped to its source file and its flag literals."""
    bins_dir = root / "rust-harness" / "runtime" / "src" / "bin"
    harness_cli = root / "rust-harness" / "harness" / "src" / "cli.rs"

    binaries: dict[str, tuple[Path, set[str]]] = {}
    sources = [(p.stem, p) for p in sorted(bins_dir.glob("*.rs"))]
    if harness_cli.is_file():
        sources.append(("harness", harness_cli))
    for name, source in sources:
        text = source.read_text(encoding="utf-8")
        binaries[name] = (source, set(FLAG_LITERAL.findall(text)))
    return binaries


def generated_pages(root: Path) -> dict[str, Path]:
    """Every page under the reference directory that says it was generated."""
    pages: dict[str, Path] = {}
    directory = root / REFERENCE_DIR
    if not directory.is_dir():
        return pages
    for page in sorted(directory.glob("*.md")):
        if GENERATED_MARKER in page.read_text(encoding="utf-8"):
            pages[page.stem] = page
    return pages


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--root", type=Path, default=REPO_ROOT, help="repository root to scan"
    )
    args = parser.parse_args()
    root = args.root.resolve()
    out = Printer()

    binaries = surface(root)
    pages = generated_pages(root)

    # The empty-set guard. An enumeration that finds no binaries would report
    # every page as orphaned and no flag as missing, which is not a result.
    if not binaries:
        out.error("site-reference: enumerated no rust-harness binaries")
        out.line("  The gate would pass without checking anything.")
        out.line(f'  Expected `Flag {{ name: "--x" }}` literals under {root}')
        return 1
    if not pages:
        out.error(f"site-reference: no generated pages under {REFERENCE_DIR}")
        out.line("  Solution: regenerate them")
        out.line("  Command: make site-gen")
        return 1

    missing_pages = sorted(name for name in binaries if name not in pages)
    orphan_pages = sorted(name for name in pages if name not in binaries)
    missing_flags: list[tuple[str, str]] = []
    for name, (_, flags) in sorted(binaries.items()):
        page = pages.get(name)
        if page is None:
            continue
        text = page.read_text(encoding="utf-8")
        for flag in sorted(flags):
            # Whole-flag match: `--control-vector` must not be satisfied by
            # `--control-vector-scale` on the same page.
            if not re.search(rf"{re.escape(flag)}(?![\w-])", text):
                missing_flags.append((name, flag))

    flag_total = sum(len(flags) for _, flags in binaries.values())
    out.info(
        f"site-reference: {len(binaries)} binaries, {flag_total} flags, "
        f"against {len(pages)} generated pages"
    )

    if not missing_pages and not orphan_pages and not missing_flags:
        out.ok("site-reference: every binary has a page that shows every flag")
        return 0

    total = len(missing_pages) + len(orphan_pages) + len(missing_flags)
    noun = "finding" if total == 1 else "findings"
    out.error(f"site-reference: {total} {noun}")
    for name in missing_pages:
        source = binaries[name][0].relative_to(root)
        out.line(f"  no page for binary {name} ({source})")
    for name in orphan_pages:
        page = pages[name].relative_to(root)
        out.line(f"  page {page} names no binary")
    for name, flag in missing_flags:
        out.line(f"  flag {flag} of {name} is absent from its page")
    out.line("  Solution: regenerate the reference pages from the binaries")
    out.line("  Command: make site-gen")
    return 1


if __name__ == "__main__":
    sys.exit(main())
