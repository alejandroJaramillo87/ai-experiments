#!/usr/bin/env python3
"""Fail the quality gate when a generated README table and the tree disagree.

The inventory tables in the tree's hub READMEs are generated by
scripts/docs/gen_inventory.py: a test directory's table from its modules'
docstrings, a package's from its modules', a hub's from its children's READMEs,
a documentation directory's from its pages. Each is committed so a reader gets
the directory's contents without running anything, which is also how it goes
stale: a module added, renamed, or given a sharper docstring ships with the
change and leaves the table describing the directory as it was.

A hand-maintained inventory has the same failure in a worse form. It is true on
the day it is written, and the description it carries is a second copy of
something the file already states in its first line -- so the two are edited
at different moments and only one of them is the one anyone reads.

This gate is the reminder, and it asks three things. First, every README carrying
an inventory marker is regenerated in memory and diffed against what is
committed, with the difference printed rather than only reported. Second, the
hubs are complete: under each root in HUB_ROOTS, the root README carries a
`dirs` table, and every child directory carries a README with an inventory
table of its own. A new subpackage, test directory or scripts directory
therefore fails the gate until it is documented. Third, the documentation
tree is routed all the way down: every directory under DOCS_ROOT has a README
that carries a `dirs` table when it has subdirectories and a `pages` table
when it has pages beside it, which is the README shape
`.styles/DOCUMENTATION_STYLE.md` states. Nothing here needs
torch, a GPU, or a collected test session, because the inputs are the files'
ASTs and the READMEs' first paragraphs.
"""

from __future__ import annotations

import argparse
import importlib.util
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent.parent
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from common.output import Printer  # noqa: E402

GENERATOR = Path(__file__).resolve().parent / "gen_inventory.py"

# The directories whose children must each be documented. Adding one here is
# the whole cost of extending the rule; the generator already renders any README.
HUB_ROOTS = ("tests", "training", "common", "scripts", "interp")

# The documentation tree, ruled by content rather than by hub: a README lists what
# sits beside it, so the directory's shape decides which tables it must carry.
DOCS_ROOT = "docs"


def load_generator(path: Path):
    """Load the generator by path; scripts/ is not an importable package."""
    spec = importlib.util.spec_from_file_location("gen_inventory", path)
    if spec is None or spec.loader is None:
        raise ImportError(f"cannot load {path}")
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


def is_documented_unit(directory: Path) -> bool:
    """A child a hub must document with a table: one holding more than its README.

    A directory kept for its README and a `.gitkeep`, such as a notebooks
    directory nothing has been checked into yet, has nothing to list.
    """
    return any(
        entry.name != "README.md" and not entry.name.startswith(".")
        for entry in directory.iterdir()
    )


def check_hubs(generator, root: Path, out: Printer) -> int:
    """The structural rule: hub tables exist and their children are documented."""
    status = 0
    for hub in HUB_ROOTS:
        hub_dir = root / hub
        readme = hub_dir / "README.md"
        if not hub_dir.is_dir():
            out.error(f"inventory: hub {hub}/ does not exist")
            status = 1
            continue
        kinds = _kinds(generator, readme, root)
        if "dirs" not in kinds:
            out.error(f"inventory: {hub}/README.md carries no inventory:dirs table")
            out.line("  Solution: add the markers and regenerate")
            out.line(f"  Command: python scripts/docs/gen_inventory.py {hub}/README.md")
            status = 1
        for child in generator.child_dirs(hub_dir):
            if not is_documented_unit(child):
                continue
            label = child.relative_to(root)
            child_kinds = _kinds(generator, child / "README.md", root)
            if not child_kinds:
                out.error(f"inventory: {label}/README.md has no inventory table")
                out.line("  Every directory under a hub is documented by a table.")
                out.line("  Solution: write the README with the markers and regenerate")
                out.line(
                    f"  Command: python scripts/docs/gen_inventory.py {label}/README.md"
                )
                status = 1
    return status


def required_kinds(generator, directory: Path) -> set[str]:
    """The tables a documentation directory's README must carry to route one level down."""
    kinds = set()
    if generator.child_dirs(directory):
        kinds.add("dirs")
    if any(
        entry.suffix == ".md" and entry.name != "README.md"
        for entry in directory.iterdir()
    ):
        kinds.add("pages")
    return kinds


def check_docs(generator, root: Path, out: Printer) -> int:
    """The documentation rule: every docs directory has a README with the tables its shape needs."""
    docs = root / DOCS_ROOT
    if not docs.is_dir():
        out.error(f"inventory: {DOCS_ROOT}/ does not exist")
        return 1
    status = 0
    pending = [docs]
    while pending:
        directory = pending.pop()
        pending.extend(generator.child_dirs(directory))
        label = directory.relative_to(root)
        readme = directory / "README.md"
        if not readme.is_file():
            out.error(f"inventory: {label}/ has no README.md")
            out.line("  Every documentation directory is routed by its README.")
            out.line(
                "  Solution: write it with the markers its shape needs and regenerate"
            )
            out.line(
                f"  Command: python scripts/docs/gen_inventory.py {label}/README.md"
            )
            status = 1
            continue
        missing = required_kinds(generator, directory) - _kinds(generator, readme, root)
        for kind in sorted(missing):
            out.error(f"inventory: {label}/README.md carries no inventory:{kind} table")
            out.line("  Solution: add the markers and regenerate")
            out.line(
                f"  Command: python scripts/docs/gen_inventory.py {label}/README.md"
            )
            status = 1
    return status


def _kinds(generator, readme: Path, root: Path) -> set[str]:
    if not readme.is_file():
        return set()
    try:
        return set(
            generator.find_blocks(
                readme.read_text(encoding="utf-8"), readme.relative_to(root)
            )
        )
    except ValueError:
        # The regeneration pass reports the malformed pair by name.
        return set()


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--root", type=Path, default=REPO_ROOT, help="repository root to scan"
    )
    args = parser.parse_args()
    root = args.root.resolve()
    out = Printer()

    if not GENERATOR.is_file():
        out.error(f"inventory: no generator at {GENERATOR}")
        return 1
    generator = load_generator(GENERATOR)

    readmes = generator.discover(root)
    # The empty-set guard: a tree with no inventories would pass without
    # checking anything, and this repository carries several.
    if not readmes:
        out.error(f"inventory: no README under {root} carries a marker")
        return 1
    status = 0
    for readme in readmes:
        status |= generator.process(readme, root, True, out)
    status |= check_hubs(generator, root, out)
    status |= check_docs(generator, root, out)
    return 1 if status else 0


if __name__ == "__main__":
    sys.exit(main())
