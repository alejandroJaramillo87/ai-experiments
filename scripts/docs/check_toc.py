#!/usr/bin/env python3
"""Fail the quality gate when a document's table of contents and its headings disagree.

The table of contents in a long document is generated by scripts/docs/gen_toc.py
from the document's own H2 and H3 headings, between one marker pair under its
`## Table of Contents` heading. It is committed so a reader gets the index without
running anything, which is also how it goes stale: a heading renamed or a section
added ships with the change and leaves a row linking an anchor that no longer
exists, in the one part of the document its editor did not reread.

This gate asks two things. First, every document carrying the marker pair is
regenerated in memory and diffed against what is committed, with the difference
printed rather than only reported. Second, every living document over the
threshold the generator states, 500 words and four sections, carries the pair,
so a page that grows past it fails the gate until it is indexed, and the remedy
is the one command the failure prints.

Frozen records are outside both rules, by the same paths the other gates exempt:
they are never edited, so they are never given a table and never asked for one.
A README is a router of a few paragraphs and two generated tables and never
needs one, and the definitions under .claude/ and the site's pages are read by
tools that index them for themselves. A marker pair in any of those is still
held fresh. Nothing here needs torch, a GPU, or a collected test session; the
inputs are the documents' own lines.
"""

from __future__ import annotations

import argparse
import importlib.util
import os
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent.parent
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from common.output import Printer  # noqa: E402

GENERATOR = Path(__file__).resolve().parent / "gen_toc.py"


def load_generator(path: Path):
    """Load the generator by path; scripts/ is not an importable package."""
    spec = importlib.util.spec_from_file_location("gen_toc", path)
    if spec is None or spec.loader is None:
        raise ImportError(f"cannot load {path}")
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


def iter_docs(generator, root: Path) -> list[Path]:
    """Every markdown file in the tree. Enumerated without git; see check_doc_refs.py."""
    found: list[Path] = []
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = [d for d in dirnames if d not in generator.PRUNE_DIRS]
        found.extend(Path(dirpath) / n for n in filenames if n.endswith(".md"))
    return sorted(found)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--root", type=Path, default=REPO_ROOT, help="repository root to scan"
    )
    args = parser.parse_args()
    root = args.root.resolve()
    out = Printer()

    if not GENERATOR.is_file():
        out.error(f"toc: no generator at {GENERATOR}")
        return 1
    generator = load_generator(GENERATOR)

    docs = iter_docs(generator, root)
    # The empty-set guard: a tree with no documents would pass without checking
    # anything.
    if not docs:
        out.error(f"toc: enumerated zero documents under {root}")
        out.line("  The gate would pass without checking anything.")
        return 1

    status = 0
    carrying = 0
    required = 0
    for doc in docs:
        rel = doc.relative_to(root)
        text = doc.read_text(encoding="utf-8", errors="replace")
        if generator.is_frozen(rel):
            continue
        if generator.carries_markers(text):
            carrying += 1
            status |= generator.process(doc, root, True, out)
            continue
        if generator.is_ruled(rel) and generator.qualifies(text):
            required += 1
            status |= generator.process(doc, root, True, out)
    out.info(
        f"toc: {len(docs)} documents, {carrying} carrying a table of contents, "
        f"{required} over the threshold without one"
    )
    return 1 if status else 0


if __name__ == "__main__":
    sys.exit(main())
