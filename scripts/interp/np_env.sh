#!/bin/bash
set -euo pipefail

# Neuronpedia env merge (interp Phase 2 PS1)
#
# Applies this repository's configuration deltas to the pinned upstream checkout:
#   1. Keys from docker/interp/neuronpedia.env-deltas replace-or-append into <src>/.env.localhost
#      (upstream's committed localhost config; `make np-clone` restores it with
#      checkout -f, so this script re-applies the deltas and is idempotent).
#   2. Secrets (HF_TOKEN, OPENAI_API_KEY) from the untracked .env.interp are written to
#      <src>/.env, the secrets file upstream's compose invocations already read.
#   3. Touches <src>/apps/graph/.env, which upstream's graph target passes as an env file.
#
# NEXT_PUBLIC_* values are baked into the webapp at image build time, so this must run
# before `make np-build` (the make targets enforce the ordering).
#
# Exit codes: 0 merged, 1 checkout or delta file missing.

RED='\033[0;31m' GREEN='\033[0;32m' YELLOW='\033[1;33m' NC='\033[0m'
if [[ -n "${NO_COLOR:-}" ]] || [[ "${1:-}" == "--no-color" ]]; then
    RED='' GREEN='' YELLOW='' NC=''
fi
print_ok()    { printf "${GREEN}[OK]${NC} %s\n" "$*"; }
print_warn()  { printf "${YELLOW}[WARN]${NC} %s\n" "$*"; }
print_error() { printf "${RED}[ERROR]${NC} %s\n" "$*"; }

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
NP_SRC="${NP_SRC:-/mnt/ai-data/interp/neuronpedia/src}"
DELTAS="$REPO_ROOT/docker/interp/neuronpedia.env-deltas"
SECRETS="$REPO_ROOT/.env.interp"
LOCALHOST_ENV="$NP_SRC/.env.localhost"
SECRETS_OUT="$NP_SRC/.env"

if [[ ! -f "$LOCALHOST_ENV" ]]; then
    print_error "Upstream checkout not found: $LOCALHOST_ENV"
    echo "  Solution: clone the pinned checkout first"
    echo "  Command: make np-clone"
    exit 1
fi
if [[ ! -f "$DELTAS" ]]; then
    print_error "Delta file not found: $DELTAS"
    exit 1
fi

# Replace-or-append each KEY=VALUE delta into .env.localhost
merged=0
while IFS= read -r line; do
    [[ "$line" =~ ^[[:space:]]*# ]] && continue
    [[ "$line" =~ ^[[:space:]]*$ ]] && continue
    key="${line%%=*}"
    if grep -q "^${key}=" "$LOCALHOST_ENV"; then
        sed -i "s|^${key}=.*|${line}|" "$LOCALHOST_ENV"
    else
        printf '%s\n' "$line" >> "$LOCALHOST_ENV"
    fi
    merged=$((merged + 1))
done < "$DELTAS"
print_ok "Merged $merged keys into $LOCALHOST_ENV"

# Secrets file: HF_TOKEN (gated Gemma weights) and OPENAI_API_KEY (explanation-search
# embeddings, optional). Written fresh each run; the checkout's .env is upstream-gitignored.
{
    echo "# Generated by scripts/interp/np_env.sh from .env.interp; do not edit or commit."
    if [[ -f "$SECRETS" ]]; then
        grep -E '^(HF_TOKEN|OPENAI_API_KEY)=' "$SECRETS" || true
    fi
} > "$SECRETS_OUT"
if [[ -f "$SECRETS" ]] && grep -q '^HF_TOKEN=..*' "$SECRETS"; then
    print_ok "Secrets written to $SECRETS_OUT"
else
    print_warn "HF_TOKEN not set; gated Gemma weights will fail to download"
    echo "  Solution: cp env.interp.example .env.interp and fill in HF_TOKEN"
fi

# Upstream's graph-localhost-dev passes apps/graph/.env as an env file; it must exist
touch "$NP_SRC/apps/graph/.env"
print_ok "Neuronpedia env merge complete"
exit 0
