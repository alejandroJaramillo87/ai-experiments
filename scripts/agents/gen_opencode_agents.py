#!/usr/bin/env python3
"""Generate .opencode/agents/*.md from .claude/agents/*.md.

Ten roles used to be authored twice: identical prompt bodies, frontmatter in two
disjoint dialects. `make agent-parity` diffed the bodies afterwards, which
detects divergence rather than preventing it -- every edit to a Claude agent was
two edits or a failed check, and the two dialects' mapping lived only in the
reader's head.

Symlinking is not an option, and the reason is recorded in
docs/agents/tooling-parity.md: OpenCode passes unknown frontmatter keys through
to the provider as model options, so Claude-dialect keys would leak into live API
calls. That argument is one-directional, though -- it says nothing about Claude
tolerating OpenCode keys -- so it rules out sharing a file while endorsing
exactly this: one source, one generated projection.

The bodies are copied verbatim; only the frontmatter is translated, by the table
below.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent.parent
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from common.output import Printer  # noqa: E402

CLAUDE_DIR = Path(".claude/agents")
OPENCODE_DIR = Path(".opencode/agents")

# Claude keys that have no OpenCode counterpart and are dropped rather than
# translated. `name` is the filename there; `model` is deliberately unset on the
# OpenCode side (see MODEL_TODO); the rest are Claude-only affordances.
DROPPED = frozenset({"name", "model", "memory", "color", "skills"})

# Marks a file as generated, and is what the fork check looks for: a file without
# it is left alone. Placed in the frontmatter as a comment, which OpenCode already
# tolerates (MODEL_TODO sits there too), so no separate sidecar is needed.
MARKER = "# Generated by `make agent-sync`"

# Emitted verbatim. OpenCode and Claude use incompatible model identifiers, so
# the OpenCode side stays unset until someone tests it against a real provider --
# the same reason the shared command files omit `model:` entirely.
MODEL_TODO = "# model: <frontier provider/model> — set during OpenCode manual testing"

# Claude `effort` -> OpenCode `options.reasoningEffort`. Not a rename: OpenCode
# has no tier above `high`, so `max` collapses onto it. bug-hunter is the one
# role that hits this, and losing the distinction is why the mapping is written
# down here instead of being rediscovered by diffing the two files.
EFFORT = {"high": "high", "max": "high"}

# Facts the table cannot express, keyed by agent name. Applied after translation.
OVERRIDES = {
    # Adversarial verification is a search for counter-evidence, not for a
    # plausible answer; sampling variance works against it. Claude Code exposes
    # no temperature control, so this exists only on the OpenCode side.
    "skeptic": {"temperature": "0"},
}


def split_frontmatter(text: str) -> tuple[dict[str, str], str]:
    """Return (frontmatter, body). Raises if the file has no frontmatter block.

    Values stay as raw strings: nothing here needs a YAML parser, and using one
    would reformat the descriptions -- which must survive byte-for-byte, since
    they are what the caller reads when choosing an agent.
    """
    lines = text.split("\n")
    if not lines or lines[0].strip() != "---":
        raise ValueError("no frontmatter: line 1 is not ---")
    try:
        end = lines.index("---", 1)
    except ValueError:
        raise ValueError("unterminated frontmatter: no closing ---") from None
    front: dict[str, str] = {}
    for line in lines[1:end]:
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        key, _, value = line.partition(":")
        front[key.strip()] = value.strip()
    return front, "\n".join(lines[end + 1 :])


def translate(name: str, front: dict[str, str]) -> list[str]:
    """Project Claude frontmatter into OpenCode's dialect.

    Key order is fixed rather than derived from the input, so the output is
    stable and a diff against the tree means a real change.
    """
    unknown = set(front) - DROPPED - {"description", "effort", "maxTurns", "tools"}
    if unknown:
        # Silence here would mean a new Claude key vanishing from OpenCode
        # unnoticed, which is the failure this generator replaces.
        raise ValueError(f"unmapped frontmatter key(s): {', '.join(sorted(unknown))}")

    out = [
        f"{MARKER} from .claude/agents/{name}.md -- edit that file, not this one.",
        f"description: {front['description']}",
        "mode: subagent",
        MODEL_TODO,
    ]

    out.extend(f"{k}: {v}" for k, v in OVERRIDES.get(name, {}).items())

    if "maxTurns" in front:
        out.append(f"steps: {front['maxTurns']}")

    if "effort" in front:
        effort = front["effort"]
        if effort not in EFFORT:
            raise ValueError(f"unmapped effort: {effort}")
        out.extend(["options:", f"  reasoningEffort: {EFFORT[effort]}"])

    # Claude grants capabilities by naming tools; OpenCode by allow/deny on two
    # coarse categories. A many-to-few projection: the read-only tools (Read,
    # Grep, Glob) have no OpenCode counterpart because they are never denied.
    tools = {t.strip() for t in front.get("tools", "").split(",")}
    writes = bool(tools & {"Edit", "Write"})
    out.extend(
        [
            "permission:",
            f"  edit: {'allow' if writes else 'deny'}",
            f"  bash: {'allow' if 'Bash' in tools else 'deny'}",
        ]
    )
    return out


def render(name: str, text: str) -> str:
    front, body = split_frontmatter(text)
    lines = ["---", *translate(name, front), "---", body.lstrip("\n")]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="report staleness without writing; exit 1 if any file would change",
    )
    parser.add_argument(
        "--force",
        action="store_true",
        help="regenerate even a forked file, discarding its local changes",
    )
    args = parser.parse_args()
    out = Printer()

    sources = sorted((REPO_ROOT / CLAUDE_DIR).glob("*.md"))
    if not sources:
        # An empty set would otherwise report success having generated nothing.
        out.error(f"agent-sync: no source agents found in {CLAUDE_DIR}")
        out.line("  Solution: run from the repository root")
        return 1

    stale: list[str] = []
    for source in sources:
        name = source.stem
        target = REPO_ROOT / OPENCODE_DIR / source.name

        # The same escape hatch command-sync gives a forked command file: a
        # deliberate OpenCode-only divergence stays possible, but must be
        # declared by removing the generated header.
        if not args.force and target.exists() and MARKER not in target.read_text():
            out.info(f"{source.name}: forked, not regenerating")
            continue

        try:
            want = render(name, source.read_text())
        except ValueError as exc:
            out.error(f"{source.name}: {exc}")
            out.line(f"  Solution: extend the mapping in {Path(__file__).name}")
            return 1

        if target.exists() and target.read_text() == want:
            out.ok(f"{source.name}: current")
            continue

        stale.append(source.name)
        if args.check:
            out.error(f"{source.name}: stale")
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(want)
            out.ok(f"{source.name}: regenerated")

    if stale and args.check:
        out.line(f"  Solution: regenerate the {len(stale)} stale file(s)")
        out.line("  Command: make agent-sync")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
