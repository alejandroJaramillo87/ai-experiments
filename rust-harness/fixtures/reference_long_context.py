"""Capture transformers' logits past the sliding window, for L5.

The rungs below this one never cross a window. L0 through L2 score one short
prompt, L3 scores in 256-token windows against an E4B attention window of 512,
and L4's continuations start from prompts of a few dozen tokens. So the two
features that are the whole architectural interest of Gemma 4 -- the
interleaved sliding/global attention split, and the shared-KV tail reading a
donor layer's older rows -- are engaged by no reference comparison in this
repository. L5 is that comparison.

`fixtures/long-context-logits.json` is not a substitute and cannot become one.
It is a change detector produced by the engine it guards, and the binary that
writes it says so: "it is not an oracle... we wrote the engine that produced
it". Its standing is that it was blessed after a transformers check, which is
this file.

The schedule is runtime/src/ladder.rs's, reproduced exactly
-----------------------------------------------------------

Both sides derive the scored positions from the checkpoint's `sliding_window`,
so which positions were scored is itself part of what L5 asserts -- a run whose
loader read a different window scores different positions and compares rows
that were computed at different places. `window_schedule` below mirrors
`ladder::window_schedule`, and runtime/tests/ladder_reference_contract.rs pins
the two together over several windows.

    window - 1    the last position whose whole prefix is still in the window
    window        the first position whose oldest token has left it
    window + 1    one past that
    2*window + 1  a second crossing
    length // 2   an interior position, well past the window
    length - 1    the end, whose row depends on the mask at every layer

The prompt must therefore be at least `4 * window + 4` tokens; the generator
refuses a shorter one rather than writing an artifact whose anchors collapse
onto each other.

Two token sources, because the two tiers cannot share one. Tier E reads the
committed corpus through the checkpoint's own tokenizer: 2052 tokens of
ordinary prose past a 512-token window, in distribution, for the reason
fixtures/reference/README.md gives for the perplexity corpus. Tier T's
checkpoint is a 288-token synthetic vocabulary with no tokenizer of its own, so
its ids are generated by the same stride build_tiny_reference.py uses -- which
keeps neighbouring positions from carrying neighbouring embeddings, where a
mask error can average away instead of showing up.

Workstation only: this loads the full checkpoint and prefills thousands of
positions in float32.

Usage:

    # Tier E, against the real checkpoint.
    .venv/bin/python3 rust-harness/fixtures/reference_long_context.py \\
        --model /mnt/ai-data/models/hf/gemma-4-E4B \\
        --out rust-harness/fixtures/reference/e4b/quick/long_context.json

    # Tier T, against the committed tiny fixture. Committed like the capture
    # beside it, because a sandbox has no torch to regenerate it with.
    .venv/bin/python3 rust-harness/fixtures/reference_long_context.py \\
        --model rust-harness/fixtures/tiny-hf-gemma4 \\
        --source synthetic --length 150 \\
        --out rust-harness/fixtures/tiny-hf-gemma4/long_context.json
"""

import argparse
import json
import sys
from pathlib import Path

from reference_common import ensure_destination, provenance

# Mirrors ladder::LONG_CONTEXT_POSITIONS. Fixed rather than derived from the
# prompt, so the rung pairs rows with positions by index and a length
# disagreement is an artifact error rather than a short comparison nobody sees.
POSITIONS = 6

CORPUS = Path(__file__).resolve().parent / "reference" / "corpus.txt"


def min_tokens(window):
    """The shortest prompt the schedule fits in. Mirrors
    ladder::min_long_context_tokens."""
    return 4 * window + 4


def window_schedule(window, length):
    """The positions to score, derived from the window.

    Mirrors ladder::window_schedule, including its refusal: a prompt that never
    outruns the window says nothing about the regime L5 exists to measure, and
    an artifact of one would report a green rung about attention that never
    slid.
    """
    if window < 1:
        raise ValueError("a sliding window of 0 has no boundary to score")
    need = min_tokens(window)
    if length < need:
        raise ValueError(
            f"a {length}-token prompt cannot cross a {window}-token window "
            f"twice -- a long-context reference needs at least {need} tokens"
        )
    positions = [
        window - 1,
        window,
        window + 1,
        2 * window + 1,
        length // 2,
        length - 1,
    ]
    # strict=False because the tail is one shorter by construction; pairing
    # every element with its successor is the intent, not a length mismatch.
    if any(a >= b for a, b in zip(positions, positions[1:], strict=False)):
        raise ValueError(f"window schedule {positions} is not strictly increasing")
    return positions


def synthetic_ids(length, vocab_size, bos_id):
    """Deterministic in-vocabulary ids for a checkpoint with no tokenizer.

    The stride is build_tiny_reference.py's PROMPT_IDS and
    conformance::golden::tokens', for the reason both give: neighbouring
    positions must not carry neighbouring embeddings, or a mask error averages
    away rather than showing up. The offset clears the control specials at the
    base of a synthetic vocabulary.

    BOS first, matching what the harness emits and what the tiny capture ran.
    """
    span = vocab_size - 8
    return [bos_id] + [(i * 37 + 11) % span + 4 for i in range(length - 1)]


def corpus_ids(tokenizer, corpus_path, length):
    """A prefix of the committed corpus, with a leading BOS.

    Prose rather than synthetic ids at Tier E, for the reason
    fixtures/reference/README.md gives: off-distribution input widens the gap
    between two implementations of one model measurably, so a divergence would
    be harder to attribute to the engine.
    """
    text = Path(corpus_path).read_text()
    ids = tokenizer(text, add_special_tokens=False)["input_ids"]
    if len(ids) < length - 1:
        raise SystemExit(
            f"[ERROR] Corpus: {corpus_path} tokenizes to {len(ids)} tokens and "
            f"this window needs {length - 1}"
        )
    return [tokenizer.bos_token_id] + ids[: length - 1]


def parse_args():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--model", required=True, help="checkpoint directory")
    p.add_argument("--out", required=True, help="destination JSON")
    p.add_argument(
        "--source",
        default="corpus",
        choices=["corpus", "synthetic"],
        help="where the prompt ids come from (default corpus, which needs the "
        "checkpoint's tokenizer)",
    )
    p.add_argument(
        "--corpus",
        default=str(CORPUS),
        help="corpus text for --source corpus (default the committed one)",
    )
    p.add_argument(
        "--length",
        type=int,
        default=0,
        help="prompt length in tokens (default 4*sliding_window + 4, the "
        "shortest the schedule fits in)",
    )
    return p.parse_args()


def main():
    args = parse_args()
    if not ensure_destination(args.out):
        return 1

    # Imported here rather than at module scope so --help works on a machine
    # without torch, which is every sandbox. runtime/tests/ladder_reference_
    # contract.rs imports this module for its constants, and does so in the
    # sandbox, so nothing above this line may need torch either.
    try:
        import torch
        from transformers import AutoModelForCausalLM, AutoTokenizer
    except ImportError as e:
        print(f"[ERROR] Import: {e}", file=sys.stderr)
        print(
            "  Solution: run on the workstation venv with torch installed",
            file=sys.stderr,
        )
        return 1

    config = json.loads((Path(args.model) / "config.json").read_text())
    # A multimodal release nests the text tower's fields; both spellings are
    # read rather than assumed, because a wrong guess here would silently score
    # a schedule derived from a window this checkpoint does not have.
    text_config = config.get("text_config", config)
    window = text_config.get("sliding_window")
    if not window:
        print(
            f"[ERROR] Config: {args.model} declares no sliding_window, so it "
            "has no boundary for L5 to score",
            file=sys.stderr,
        )
        return 1
    length = args.length or min_tokens(window)
    try:
        positions = window_schedule(window, length)
    except ValueError as e:
        print(f"[ERROR] Schedule: {e}", file=sys.stderr)
        print(
            f"  Solution: pass --length {min_tokens(window)} or more", file=sys.stderr
        )
        return 1
    print(
        f"[OK] Window: {window} tokens, scoring {positions} of {length}",
        file=sys.stderr,
    )

    if args.source == "synthetic":
        ids = synthetic_ids(
            length, text_config["vocab_size"], text_config.get("bos_token_id", 2)
        )
    else:
        print(f"[RUN] Load tokenizer: {args.model}", file=sys.stderr)
        ids = corpus_ids(AutoTokenizer.from_pretrained(args.model), args.corpus, length)
    print(f"[OK] Prompt: {len(ids)} ids from {args.source}", file=sys.stderr)

    print(
        "[RUN] Load model: float32 on cpu, this reads the whole file",
        file=sys.stderr,
    )
    model = AutoModelForCausalLM.from_pretrained(
        args.model,
        dtype=torch.float32,
        device_map="cpu",
        # Eager, so the comparison is against the reference formulation of
        # attention rather than against a fused kernel's rounding -- and at
        # this length, against the reference formulation of the sliding mask,
        # which is the whole subject of this artifact.
        attn_implementation="eager",
    )
    model.eval()

    # One pass over the whole prompt. The rows are taken from it rather than
    # from a cached decode, so the reference makes no claim about incremental
    # attention -- that difference is the engine's to answer for, and folding it
    # into the oracle would let a caching bug agree with itself.
    print(f"[RUN] Forward pass: {len(ids)} positions", file=sys.stderr)
    with torch.no_grad():
        logits = model(torch.tensor([ids])).logits[0]

    rows = [
        {"position": p, "logits": logits[p].detach().to(torch.float32).tolist()}
        for p in positions
    ]

    payload = {
        "sliding_window": window,
        "length": length,
        "source": args.source,
        "add_bos": True,
        "dtype": "float32",
        "token_ids": list(ids),
        "rows": rows,
        **provenance(args.model),
    }
    Path(args.out).write_text(json.dumps(payload))
    print(
        f"[OK] Wrote {args.out}: {len(rows)} rows of {len(rows[0]['logits'])} "
        f"across a {window}-token window",
        file=sys.stderr,
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
