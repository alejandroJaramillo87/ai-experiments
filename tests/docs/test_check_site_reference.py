"""Tests for scripts/docs/check_site_reference.py.

The gate holds the committed reference pages under site/docs to the flag
tables they were generated from. Three findings and one guard carry it: a
binary with no page, a generated page for a binary that no longer exists, a
flag the binary accepts that its page does not show, and the empty enumeration
that would otherwise report a tree with no binaries as fully documented.

Fixtures are scratch trees rather than the real repository, so the tests do not
turn red the next time a flag is added.

The module is loaded by path; scripts/ is not an importable package.
"""

from __future__ import annotations

import importlib.util
import subprocess
import sys
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parents[2]
SCRIPT = REPO_ROOT / "scripts" / "docs" / "check_site_reference.py"

BIN_SOURCE = """\
const SPEC: Spec = Spec {
    flags: &[
        Flag { name: "--help", kind: Kind::Bare, help: "print this help" },
        Flag { name: "--model", kind: Kind::Value("<dir>"), help: "checkpoint" },
        Flag { name: "--control-vector", kind: Kind::Value("<p>"), help: "steer" },
    ],
};
"""

MARKER = "Generated by `make site-gen` from `x --help`."


def page(*flags: str) -> str:
    body = "\n".join(f"  {flag} <v>" for flag in flags)
    return f"# x\n\n{MARKER}\n\n```text\nusage: x\n\nOptions:\n{body}\n```\n"


@pytest.fixture(scope="module")
def mod():
    spec = importlib.util.spec_from_file_location("check_site_reference", SCRIPT)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def run_gate(root: Path) -> subprocess.CompletedProcess[str]:
    """The gate as the quality target runs it, scoped to a scratch tree."""
    return subprocess.run(
        [sys.executable, str(SCRIPT), "--root", str(root)],
        capture_output=True,
        text=True,
        env={"NO_COLOR": "1", "PATH": "/usr/bin:/bin"},
    )


def scratch_tree(root: Path, bins: dict[str, str], pages: dict[str, str]) -> None:
    """A tree shaped like the workspace: bin sources and reference pages."""
    bins_dir = root / "rust-harness" / "runtime" / "src" / "bin"
    bins_dir.mkdir(parents=True)
    for name, text in bins.items():
        (bins_dir / f"{name}.rs").write_text(text, encoding="utf-8")
    harness_cli = root / "rust-harness" / "harness" / "src" / "cli.rs"
    harness_cli.parent.mkdir(parents=True)
    harness_cli.write_text(BIN_SOURCE, encoding="utf-8")
    ref = root / "site" / "docs" / "rust-harness" / "reference"
    ref.mkdir(parents=True)
    for name, text in pages.items():
        (ref / f"{name}.md").write_text(text, encoding="utf-8")


FULL = page("--help", "--model", "--control-vector")


class TestSurface:
    """What the enumeration collects."""

    def test_harness_is_a_binary_though_it_has_no_bin_file(self, mod, tmp_path):
        scratch_tree(tmp_path, {"layer-diff": BIN_SOURCE}, {})
        binaries = mod.surface(tmp_path)
        assert set(binaries) == {"layer-diff", "harness"}
        assert "--model" in binaries["harness"][1]

    def test_a_hand_written_page_is_not_a_generated_one(self, mod, tmp_path):
        scratch_tree(
            tmp_path,
            {"layer-diff": BIN_SOURCE},
            {"index": "# Reference\n\nHand-written.\n", "harness": FULL},
        )
        assert set(mod.generated_pages(tmp_path)) == {"harness"}


class TestGate:
    """End to end, over a scratch tree."""

    def test_a_complete_tree_passes(self, tmp_path):
        scratch_tree(
            tmp_path, {"layer-diff": BIN_SOURCE}, {"layer-diff": FULL, "harness": FULL}
        )
        result = run_gate(tmp_path)
        assert result.returncode == 0, result.stderr

    def test_a_binary_without_a_page_fails(self, tmp_path):
        scratch_tree(tmp_path, {"layer-diff": BIN_SOURCE}, {"harness": FULL})
        result = run_gate(tmp_path)
        assert result.returncode == 1
        assert "no page for binary layer-diff" in result.stderr

    def test_a_generated_page_for_a_retired_binary_fails(self, tmp_path):
        scratch_tree(
            tmp_path,
            {"layer-diff": BIN_SOURCE},
            {"layer-diff": FULL, "harness": FULL, "old-tool": FULL},
        )
        result = run_gate(tmp_path)
        assert result.returncode == 1
        assert "old-tool.md names no binary" in result.stderr

    def test_a_flag_absent_from_its_page_fails(self, tmp_path):
        scratch_tree(
            tmp_path,
            {"layer-diff": BIN_SOURCE},
            {"layer-diff": page("--help", "--model"), "harness": FULL},
        )
        result = run_gate(tmp_path)
        assert result.returncode == 1
        assert "flag --control-vector of layer-diff is absent" in result.stderr

    def test_a_flag_is_matched_whole(self, tmp_path):
        """`--control-vector-scale` on the page must not satisfy `--control-vector`."""
        scratch_tree(
            tmp_path,
            {"layer-diff": BIN_SOURCE},
            {
                "layer-diff": page("--help", "--model", "--control-vector-scale"),
                "harness": FULL,
            },
        )
        result = run_gate(tmp_path)
        assert result.returncode == 1
        assert "flag --control-vector of layer-diff is absent" in result.stderr

    def test_an_empty_enumeration_fails_rather_than_passing(self, tmp_path):
        (tmp_path / "site" / "docs" / "rust-harness" / "reference").mkdir(parents=True)
        result = run_gate(tmp_path)
        assert result.returncode == 1
        assert "enumerated no rust-harness binaries" in result.stderr

    def test_no_generated_pages_fails_and_names_the_target(self, tmp_path):
        scratch_tree(tmp_path, {"layer-diff": BIN_SOURCE}, {})
        result = run_gate(tmp_path)
        assert result.returncode == 1
        assert "make site-gen" in result.stderr


def test_the_repository_reference_pages_are_current():
    """The real gate over the whole tree, as every sibling module ends."""
    result = run_gate(REPO_ROOT)
    assert result.returncode == 0, result.stderr
