"""Tests for scripts/docs/gen_site_reference.py.

The generator parses each binary's --help and renders a page of tables. The
parser is tested against two inline fixtures shaped like the two renderers, the
harness's grouped help with wrapped descriptions and a runtime Spec's flat
option list, so the tests need no cargo and do not turn red when a flag is
added to a real binary.

The module is loaded by path; scripts/ is not an importable package.
"""

from __future__ import annotations

import importlib.util
import re
import sys
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parents[2]
SCRIPT = REPO_ROOT / "scripts" / "docs" / "gen_site_reference.py"

HARNESS_HELP = """\
usage: harness --model <checkpoint-dir> [--trace-level <info|debug|trace>] (--chat | <task description>)

Run a coding task, a chat REPL, or an HTTP server against a local
Gemma 4 checkpoint on the CPU backend.

Mode:
  --chat
      interactive REPL instead of a one-shot task; takes no task text

Model:
  --model <checkpoint-dir>
      config.json and model.safetensors for the CPU backend; a path to the
      weights file resolves to its directory

Diagnostics:
  --trace-level <info|debug|trace>
      span verbosity (default info); requires --trace-chrome

Everything after a bare -- is task text, even if it starts with a dash.

Other binaries in this workspace:
  harness
      the coding agent loop, the chat REPL, and the OpenAI-shaped server
  ladder
      the seven-rung correctness gate against a transformers reference
  retired-tool
      a binary with no page
"""

LADDER_HELP = """\
usage: ladder --model <checkpoint-dir> [--batch stepped|whole|<n>] [--text-only]

Run the seven-rung correctness gate against a transformers reference.

Options:
  --help
      print this help and exit
  --model <checkpoint-dir>
      the checkpoint to climb; required
  --batch stepped|whole|<n>
      how many positions one forward pass covers
  --text-only
      treat a multimodal checkpoint as its text tower
"""


@pytest.fixture(scope="module")
def mod():
    spec = importlib.util.spec_from_file_location("gen_site_reference", SCRIPT)
    module = importlib.util.module_from_spec(spec)
    # Registered before execution: the script's dataclasses resolve their
    # postponed annotations through sys.modules, and an unregistered module
    # fails at class creation rather than at use.
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


class TestParseHelp:
    def test_sections_come_in_help_order_with_their_titles(self, mod):
        parsed = mod.parse_help(HARNESS_HELP)
        assert [s.title for s in parsed.sections] == [
            "Mode",
            "Model",
            "Diagnostics",
            "Other binaries in this workspace",
        ]

    def test_usage_summary_and_trailing_prose_are_separated(self, mod):
        parsed = mod.parse_help(HARNESS_HELP)
        assert parsed.usage.startswith("usage: harness --model")
        assert parsed.summary == [
            "Run a coding task, a chat REPL, or an HTTP server against a local "
            "Gemma 4 checkpoint on the CPU backend."
        ]
        assert parsed.trailing == [
            "Everything after a bare -- is task text, even if it starts with a dash."
        ]

    def test_a_wrapped_description_joins_into_one_string(self, mod):
        parsed = mod.parse_help(HARNESS_HELP)
        term, description = parsed.sections[1].entries[0]
        assert term == "--model <checkpoint-dir>"
        assert description.endswith(
            "a path to the weights file resolves to its directory"
        )

    def test_a_flat_spec_help_has_one_options_section(self, mod):
        parsed = mod.parse_help(LADDER_HELP)
        assert [s.title for s in parsed.sections] == ["Options"]
        assert len(parsed.sections[0].entries) == 4
        assert parsed.trailing == []

    def test_text_without_a_usage_line_is_refused(self, mod):
        with pytest.raises(ValueError):
            mod.parse_help("Options:\n  --x\n      y\n")


class TestRenderPage:
    def test_marker_line_names_the_binary_and_its_source(self, mod):
        page = mod.render_page(
            "ladder",
            "rust-harness/runtime/src/bin/ladder.rs",
            mod.parse_help(LADDER_HELP),
            {"ladder"},
        )
        assert "Generated by `make site-gen` from `ladder --help`." in page
        assert "`rust-harness/runtime/src/bin/ladder.rs`" in page

    def test_pipes_in_a_placeholder_are_escaped_inside_the_code_cell(self, mod):
        page = mod.render_page("ladder", "x.rs", mod.parse_help(LADDER_HELP), set())
        assert "| `--batch stepped\\|whole\\|<n>` |" in page
        assert "| `--trace-level <info\\|debug\\|trace>` |" in mod.render_page(
            "harness", "x.rs", mod.parse_help(HARNESS_HELP), set()
        )

    def test_every_flag_appears_whole_so_the_gate_accepts_the_page(self, mod):
        page = mod.render_page("harness", "x.rs", mod.parse_help(HARNESS_HELP), set())
        for flag in ("--chat", "--model", "--trace-level"):
            assert re.search(rf"{re.escape(flag)}(?![\w-])", page), flag

    def test_usage_is_the_one_fenced_block(self, mod):
        page = mod.render_page("ladder", "x.rs", mod.parse_help(LADDER_HELP), set())
        assert page.count("```") == 2
        assert "## Usage\n\n```text\nusage: ladder" in page

    def test_binaries_table_links_siblings_with_pages_and_not_itself(self, mod):
        page = mod.render_page(
            "harness", "x.rs", mod.parse_help(HARNESS_HELP), {"harness", "ladder"}
        )
        assert "| Binary | Purpose |" in page
        assert "| [ladder](ladder.md) |" in page
        assert "| harness |" in page
        assert "| retired-tool |" in page

    def test_angle_brackets_in_prose_cells_are_escaped(self, mod):
        help_text = mod.parse_help(
            "usage: x\n\nsummary\n\nOptions:\n  --n <n>\n      a value like <n>\n"
        )
        page = mod.render_page("x", "x.rs", help_text, set())
        assert "| `--n <n>` | a value like &lt;n&gt; |" in page


class TestBinaries:
    def test_harness_and_each_bin_file_are_found(self, mod, tmp_path):
        (tmp_path / "rust-harness" / "harness" / "src").mkdir(parents=True)
        (tmp_path / "rust-harness" / "harness" / "src" / "cli.rs").write_text("")
        bins = tmp_path / "rust-harness" / "runtime" / "src" / "bin"
        bins.mkdir(parents=True)
        (bins / "ladder.rs").write_text("")
        (bins / "tiny-model.rs").write_text("")
        assert mod.binaries(tmp_path) == [
            ("harness", "harness", "rust-harness/harness/src/cli.rs"),
            ("ladder", "runtime", "rust-harness/runtime/src/bin/ladder.rs"),
            ("tiny-model", "runtime", "rust-harness/runtime/src/bin/tiny-model.rs"),
        ]

    def test_an_empty_tree_finds_nothing(self, mod, tmp_path):
        assert mod.binaries(tmp_path) == []
