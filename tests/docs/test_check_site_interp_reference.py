"""Tests for scripts/docs/check_site_interp_reference.py.

The gate holds the committed interp reference pages under site/docs to the
argparse literals they were generated from. Three findings and one guard carry
it: a verb with no page, a generated page for a verb that no longer exists, a
flag the verb accepts that its page does not show, and the empty enumeration
that would otherwise report a tree with no verbs as fully documented. A fourth
case is the delegated verb: a module whose parser lives in common/obs.

Fixtures are scratch trees rather than the real repository, so the tests do not
turn red the next time a flag is added.

The module is loaded by path; scripts/ is not an importable package.
"""

from __future__ import annotations

import importlib.util
import subprocess
import sys
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parents[2]
SCRIPT = REPO_ROOT / "scripts" / "docs" / "check_site_interp_reference.py"

TRAIN_SOURCE = '''\
def configure(sub) -> None:
    p = sub.add_parser(
        "probe-train",
        help="train probes",
    )
    p.add_argument("--capture", required=True)
    p.add_argument(
        "--model-hash",
        default=None,
    )
    p.set_defaults(func=cmd)
'''

RUNS_SOURCE = '''\
from common.obs import runs


def configure(sub) -> None:
    runs.configure(sub, "interp")
'''

OBS_RUNS_SOURCE = '''\
def add_arguments(parser) -> None:
    parser.add_argument("-n", "--limit", type=int, default=20)
    parser.add_argument("--failed", action="store_true")


def configure(sub, cli: str) -> None:
    p = sub.add_parser("runs", help="list runs")
    add_arguments(p)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--cli", required=True)
    add_arguments(parser)
'''

MARKER = "Generated by `make site-gen` from `python -m interp x --help`."


def page(*flags: str) -> str:
    body = "\n".join(f"| `{flag} V` | | |" for flag in flags)
    return f"# x\n\n{MARKER}\n\n## Flags\n\n| Flag | Description | Default |\n|-|-|-|\n{body}\n"


@pytest.fixture(scope="module")
def mod():
    spec = importlib.util.spec_from_file_location("check_site_interp_reference", SCRIPT)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def run_gate(root: Path) -> subprocess.CompletedProcess[str]:
    """The gate as the quality target runs it, scoped to a scratch tree."""
    return subprocess.run(
        [sys.executable, str(SCRIPT), "--root", str(root)],
        capture_output=True,
        text=True,
        env={"NO_COLOR": "1", "PATH": "/usr/bin:/bin"},
    )


def scratch_tree(root: Path, modules: dict[str, str], pages: dict[str, str]) -> None:
    """A tree shaped like the repository: command modules and reference pages."""
    commands = root / "interp" / "commands"
    commands.mkdir(parents=True)
    (commands / "__init__.py").write_text("", encoding="utf-8")
    for name, text in modules.items():
        (commands / f"{name}.py").write_text(text, encoding="utf-8")
    obs = root / "common" / "obs"
    obs.mkdir(parents=True)
    (obs / "runs.py").write_text(OBS_RUNS_SOURCE, encoding="utf-8")
    ref = root / "site" / "docs" / "interp" / "reference"
    ref.mkdir(parents=True)
    for name, text in pages.items():
        (ref / f"{name}.md").write_text(text, encoding="utf-8")


TRAIN_PAGE = page("--capture", "--model-hash")
RUNS_PAGE = page("--limit", "--failed")


class TestSurface:
    """What the enumeration collects."""

    def test_verb_and_flags_come_from_the_argparse_literals(self, mod, tmp_path):
        scratch_tree(tmp_path, {"probe_train": TRAIN_SOURCE}, {})
        verbs = mod.surface(tmp_path)
        assert set(verbs) == {"probe-train"}
        assert verbs["probe-train"][1] == {"--capture", "--model-hash"}

    def test_a_delegated_verb_is_read_from_common_obs_without_its_main(self, mod, tmp_path):
        scratch_tree(tmp_path, {"runs": RUNS_SOURCE}, {})
        verbs = mod.surface(tmp_path)
        assert set(verbs) == {"runs"}
        assert verbs["runs"][1] == {"--limit", "--failed"}

    def test_a_hand_written_page_is_not_a_generated_one(self, mod, tmp_path):
        scratch_tree(
            tmp_path,
            {"probe_train": TRAIN_SOURCE},
            {"index": "# Reference\n\nHand-written.\n", "probe-train": TRAIN_PAGE},
        )
        assert set(mod.generated_pages(tmp_path)) == {"probe-train"}


class TestGate:
    """End to end, over a scratch tree."""

    def test_a_complete_tree_passes(self, tmp_path):
        scratch_tree(
            tmp_path,
            {"probe_train": TRAIN_SOURCE, "runs": RUNS_SOURCE},
            {"probe-train": TRAIN_PAGE, "runs": RUNS_PAGE},
        )
        result = run_gate(tmp_path)
        assert result.returncode == 0, result.stderr

    def test_a_verb_without_a_page_fails(self, tmp_path):
        scratch_tree(
            tmp_path, {"probe_train": TRAIN_SOURCE, "runs": RUNS_SOURCE}, {"runs": RUNS_PAGE}
        )
        result = run_gate(tmp_path)
        assert result.returncode == 1
        assert "no page for verb probe-train" in result.stderr

    def test_a_generated_page_for_a_retired_verb_fails(self, tmp_path):
        scratch_tree(
            tmp_path,
            {"probe_train": TRAIN_SOURCE},
            {"probe-train": TRAIN_PAGE, "old-verb": TRAIN_PAGE},
        )
        result = run_gate(tmp_path)
        assert result.returncode == 1
        assert "old-verb.md names no verb" in result.stderr

    def test_a_flag_absent_from_its_page_fails(self, tmp_path):
        scratch_tree(tmp_path, {"probe_train": TRAIN_SOURCE}, {"probe-train": page("--capture")})
        result = run_gate(tmp_path)
        assert result.returncode == 1
        assert "flag --model-hash of probe-train is absent" in result.stderr

    def test_a_flag_is_matched_whole(self, tmp_path):
        """`--model-hash` on the page must not satisfy a `--model` the verb accepts."""
        source = TRAIN_SOURCE.replace('"--capture"', '"--model"')
        scratch_tree(tmp_path, {"probe_train": source}, {"probe-train": page("--model-hash")})
        result = run_gate(tmp_path)
        assert result.returncode == 1
        assert "flag --model of probe-train is absent" in result.stderr

    def test_an_empty_enumeration_fails_loudly(self, tmp_path):
        scratch_tree(tmp_path, {}, {"probe-train": TRAIN_PAGE})
        result = run_gate(tmp_path)
        assert result.returncode == 1
        assert "enumerated no interp verbs" in result.stderr
