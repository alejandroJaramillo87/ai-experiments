"""Tests for scripts/docs/gen_site_interp_reference.py.

The generator walks an argparse parser and renders a page of tables. It is
tested against an inline fixture parser shaped like the interp CLI, one flat
verb and one with nested subcommands, so the tests need no interp environment
and do not turn red when a flag is added to a real command.

The module is loaded by path; scripts/ is not an importable package.
"""

from __future__ import annotations

import argparse
import importlib.util
import re
import sys
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parents[2]
SCRIPT = REPO_ROOT / "scripts" / "docs" / "gen_site_interp_reference.py"


@pytest.fixture(scope="module")
def mod():
    spec = importlib.util.spec_from_file_location("gen_site_interp_reference", SCRIPT)
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


def flat_parser() -> argparse.ArgumentParser:
    """A verb shaped like probe-train: required flags, defaults, a store_true."""
    root = argparse.ArgumentParser(prog="python -m interp")
    sub = root.add_subparsers(dest="command")
    p = sub.add_parser(
        "probe-train",
        description="Train per-layer probes.\n\nCPU work over cached\nactivations.",
    )
    p.add_argument("--capture", required=True, help="capture directory")
    p.add_argument("--out", default="/mnt/ai-data/interp/probes")
    p.add_argument("--seed", type=int, default=0, help="a|b")
    p.add_argument("--dry-run", action="store_true", help="list <what> would change")
    p.add_argument("--override", action="append", default=[], help="repeatable")
    return sub.choices["probe-train"]


def nested_parser() -> argparse.ArgumentParser:
    """A verb shaped like organism: subcommands with their own flags."""
    root = argparse.ArgumentParser(prog="python -m interp")
    sub = root.add_subparsers(dest="command")
    p = sub.add_parser("organism", description="Pipeline driver.")
    osub = p.add_subparsers(dest="organism_command", required=True)
    gen = osub.add_parser("generate", description="Draw ground truth.")
    gen.add_argument("--recipe", required=True)
    seal = osub.add_parser("seal", description="Seal it.")
    seal.add_argument("--recipe", required=True)
    seal.add_argument("--gguf", default=None, help="optional")
    return sub.choices["organism"]


class TestRenderPage:
    def test_marker_line_names_the_verb_and_its_source(self, mod):
        page = mod.render_page("probe-train", "interp/commands/probe_train.py", flat_parser())
        assert (
            "Generated by `make site-gen` from `python -m interp probe-train --help`."
            in page
        )
        assert "`interp/commands/probe_train.py`" in page

    def test_description_paragraphs_are_unwrapped(self, mod):
        page = mod.render_page("probe-train", "x.py", flat_parser())
        assert "Train per-layer probes.\n\nCPU work over cached activations.\n" in page

    def test_usage_is_the_one_fenced_block(self, mod):
        page = mod.render_page("probe-train", "x.py", flat_parser())
        assert page.count("```") == 2
        assert "## Usage\n\n```text\nusage: python -m interp probe-train" in page

    def test_required_defaults_and_store_true_render_as_the_help_would(self, mod):
        page = mod.render_page("probe-train", "x.py", flat_parser())
        assert "| `--capture CAPTURE` | capture directory | required |" in page
        assert "| `--out OUT` |  | `/mnt/ai-data/interp/probes` |" in page
        assert "| `--seed SEED` | a\\|b | `0` |" in page
        assert "| `--dry-run` | list &lt;what&gt; would change |  |" in page
        assert "| `--override OVERRIDE` | repeatable |  |" in page

    def test_every_flag_appears_whole_so_the_gate_accepts_the_page(self, mod):
        page = mod.render_page("probe-train", "x.py", flat_parser())
        for flag in ("--capture", "--out", "--seed", "--dry-run", "--override"):
            assert re.search(rf"{re.escape(flag)}(?![\w-])", page), flag

    def test_nested_subcommands_become_sections_in_parser_order(self, mod):
        page = mod.render_page("organism", "x.py", nested_parser())
        assert page.index("## organism generate") < page.index("## organism seal")
        assert "### Usage\n\n```text\nusage: python -m interp organism seal" in page
        assert "| `--gguf GGUF` | optional |  |" in page
        assert page.count("```") == 6

    def test_rendering_is_deterministic(self, mod):
        first = mod.render_page("organism", "x.py", nested_parser())
        second = mod.render_page("organism", "x.py", nested_parser())
        assert first == second


class TestVerbs:
    def test_every_command_module_registers_exactly_one_verb(self, mod):
        """The pairing of verb to source file rests on this."""
        found = mod.verbs(REPO_ROOT)
        names = [verb for verb, _, _ in found]
        assert len(names) == len(set(names))
        assert "probe-train" in names
        for _, source, _ in found:
            assert source.startswith("interp/commands/"), source
